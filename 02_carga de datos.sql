  FUNCTION muestrear(p_acum IN t_num, p_n IN PLS_INTEGER) RETURN PLS_INTEGER IS
    x   NUMBER := DBMS_RANDOM.VALUE(0, p_acum(p_n));
    lo  PLS_INTEGER := 1;
    hi  PLS_INTEGER := p_n;
    mid PLS_INTEGER;
  BEGIN
    WHILE lo < hi LOOP
      mid := TRUNC((lo + hi) / 2);
      IF p_acum(mid) < x THEN lo := mid + 1; ELSE hi := mid; END IF;
    END LOOP;
    RETURN lo;
  END;

  -- Dice si la habitación está libre todas las noches del rango
  FUNCTION libre(p_hab NUMBER, p_in DATE, p_out DATE) RETURN BOOLEAN IS
  BEGIN
    FOR x IN (p_in - c_base) .. (p_out - c_base - 1) LOOP
      IF v_ocupado.EXISTS(p_hab * 2000 + x) THEN
        RETURN FALSE;
      END IF;
    END LOOP;
    RETURN TRUE;
  END;

  -- Marca las noches del rango como ocupadas
  PROCEDURE ocupar(p_hab NUMBER, p_in DATE, p_out DATE) IS
  BEGIN
    FOR x IN (p_in - c_base) .. (p_out - c_base - 1) LOOP
      v_ocupado(p_hab * 2000 + x) := TRUE;
    END LOOP;
  END;

  -- Suma la tarifa de cada noche según su temporada
  FUNCTION valor_estadia(p_hab NUMBER, p_in DATE, p_out DATE) RETURN NUMBER IS
    s NUMBER := 0;
  BEGIN
    FOR x IN (p_in - c_base) .. (p_out - c_base - 1) LOOP
      s := s + v_tarifa(p_hab * 100 + v_cal_temp(x));
    END LOOP;
    RETURN s;
  END;

  -- Método de pago: en línea al reservar o en el sitio al llegar
  FUNCTION metodo_pago(p_en_sitio BOOLEAN) RETURN VARCHAR2 IS
    x NUMBER := DBMS_RANDOM.VALUE;
  BEGIN
    IF p_en_sitio THEN
      RETURN CASE WHEN x < 0.40 THEN 'EFECTIVO' WHEN x < 0.75 THEN 'TARJETA_DEBITO' ELSE 'TARJETA_CREDITO' END;
    END IF;
    RETURN CASE WHEN x < 0.38 THEN 'TARJETA_CREDITO' WHEN x < 0.66 THEN 'PSE'
                WHEN x < 0.84 THEN 'TRANSFERENCIA' ELSE 'TARJETA_DEBITO' END;
  END;

  PROCEDURE pagar(p_res NUMBER, p_fecha DATE, p_monto NUMBER, p_metodo VARCHAR2, p_estado VARCHAR2) IS
  BEGIN
    INSERT INTO pago (id_reserva, fecha_pago, monto, metodo, estado)
    VALUES (p_res, p_fecha, ROUND(p_monto), p_metodo, p_estado);
  END;

BEGIN
  -- 9.1 Calendario y tarifas en memoria
  FOR rc IN (SELECT cal.fecha - c_base AS dia, cal.id_temporada, t.categoria
             FROM calendario cal JOIN temporada t ON t.id_temporada = cal.id_temporada)
  LOOP
    v_cal_temp(rc.dia) := rc.id_temporada;
    v_cal_cat(rc.dia)  := rc.categoria;
  END LOOP;

  FOR rt IN (SELECT id_habitacion, id_temporada, valor_noche FROM tarifa) LOOP
    v_tarifa(rt.id_habitacion * 100 + rt.id_temporada) := rt.valor_noche;
  END LOOP;

  -- 9.2 Pesos de los días de llegada
  v_acum := 0;
  FOR dd IN 0 .. (c_fin - c_base) LOOP
    w := CASE v_cal_cat(dd) WHEN 'ALTA' THEN 4 WHEN 'MEDIA' THEN 2 ELSE 1 END;
    -- MOD(dd, 7): 0 = lunes (01/01/2024 fue lunes) ... 4 = viernes, 5 = sábado, 6 = domingo
    w := w * CASE MOD(dd, 7) WHEN 4 THEN 2.2 WHEN 5 THEN 1.8 WHEN 3 THEN 1.2 WHEN 6 THEN 0.7 ELSE 0.8 END;
    w := w * CASE EXTRACT(YEAR FROM c_base + dd) WHEN 2024 THEN 0.85 WHEN 2025 THEN 1.00 ELSE 1.15 END;
    IF c_base + dd > c_corte THEN
      w := w * 0.45;
    END IF;
    v_acum := v_acum + w;
    v_n_dias := v_n_dias + 1;
    v_dia_acum(v_n_dias) := v_acum;
  END LOOP;

  -- 9.3 Alojamientos y su peso
  v_acum := 0;
  FOR ra IN (SELECT al.id_alojamiento, m.nombre AS municipio, t.nombre AS tipo,
                    (SELECT COUNT(*) FROM habitacion h WHERE h.id_alojamiento = al.id_alojamiento) AS n_hab
             FROM alojamiento al
             JOIN municipio m        ON m.id_municipio = al.id_municipio
             JOIN tipo_alojamiento t ON t.id_tipo = al.id_tipo
             ORDER BY al.id_alojamiento)
  LOOP
    v_n_aloj := v_n_aloj + 1;
    v_aloj_id(v_n_aloj) := ra.id_alojamiento;
    v_aloj_idx(ra.id_alojamiento) := v_n_aloj;

    w := CASE
           WHEN ra.municipio = 'Salento'          THEN 1.70
           WHEN ra.municipio = 'Montenegro'       THEN 1.45
           WHEN ra.municipio = 'Filandia'         THEN 1.35
           WHEN ra.municipio = 'Quimbaya'         THEN 1.30
           WHEN ra.municipio = 'Armenia'          THEN 1.00
           WHEN ra.municipio = 'La Tebaida'       THEN 0.90
           WHEN ra.municipio LIKE 'Calarc%'       THEN 0.80
           WHEN ra.municipio = 'Circasia'         THEN 0.70
           ELSE 0.45   -- Buenavista, Córdoba, Génova, Pijao
         END
       * CASE ra.tipo
           WHEN 'Glamping'       THEN 1.50
           WHEN 'Finca cafetera' THEN 1.30
           WHEN 'Hostal'         THEN 1.10
           WHEN 'Hotel'          THEN 0.70
           ELSE 1.00
         END
       * POWER(ra.n_hab, 0.7)
       * DBMS_RANDOM.VALUE(0.4, 1.6);
    v_acum := v_acum + w;
    v_aloj_acum(v_n_aloj) := v_acum;

    v_aloj_p_resena(v_n_aloj) := DBMS_RANDOM.VALUE(0.30, 0.80);
    v_aloj_calidad(v_n_aloj)  := DBMS_RANDOM.VALUE(2.6, 4.9);
  END LOOP;

  -- 9.4 Habitaciones y servicios de cada alojamiento
  k := 0;
  FOR rh IN (SELECT id_habitacion, id_alojamiento, capacidad FROM habitacion ORDER BY id_alojamiento, id_habitacion) LOOP
    k := k + 1;
    v_hab_id(k)  := rh.id_habitacion;
    v_hab_cap(k) := rh.capacidad;
    i := v_aloj_idx(rh.id_alojamiento);
    IF NOT v_aloj_hab_ini.EXISTS(i) THEN
      v_aloj_hab_ini(i) := k;
      v_aloj_hab_n(i)   := 0;
    END IF;
    v_aloj_hab_n(i) := v_aloj_hab_n(i) + 1;
  END LOOP;

  k := 0;
  FOR rs IN (SELECT id_servicio, id_alojamiento, precio FROM servicio ORDER BY id_alojamiento, id_servicio) LOOP
    k := k + 1;
    v_srv_id(k)     := rs.id_servicio;
    v_srv_precio(k) := rs.precio;
    i := v_aloj_idx(rs.id_alojamiento);
    IF NOT v_aloj_srv_ini.EXISTS(i) THEN
      v_aloj_srv_ini(i) := k;
      v_aloj_srv_n(i)   := 0;
    END IF;
    v_aloj_srv_n(i) := v_aloj_srv_n(i) + 1;
  END LOOP;

  FOR rcl IN (SELECT id_cliente FROM cliente ORDER BY id_cliente) LOOP
    v_n_cli := v_n_cli + 1;
    v_cli_id(v_n_cli) := rcl.id_cliente;
  END LOOP;

  -- 9.5 Generar las reservas
  WHILE v_reservas < c_min_reservas OR v_lineas_srv < c_min_servicios LOOP
    v_intentos := v_intentos + 1;
    IF v_intentos > 300000 THEN
      RAISE_APPLICATION_ERROR(-20020, 'Demasiados intentos: revisar capacidad de habitaciones');
    END IF;

    -- Alojamiento, fecha de llegada y noches
    ia   := muestrear(v_aloj_acum, v_n_aloj);
    d    := muestrear(v_dia_acum, v_n_dias) - 1;
    v_in := c_base + d;

    r := DBMS_RANDOM.VALUE;
    v_noches := CASE WHEN r < 0.25 THEN 1 WHEN r < 0.60 THEN 2 WHEN r < 0.80 THEN 3
                     WHEN r < 0.90 THEN 4 ELSE TRUNC(DBMS_RANDOM.VALUE(5, 8)) END;
    IF v_cal_cat(d) = 'ALTA' AND DBMS_RANDOM.VALUE < 0.35 THEN
      v_noches := v_noches + 1;   -- en temporada alta la gente se queda más
    END IF;
    v_out := v_in + v_noches;

    -- Estado coherente con la fecha de corte
    r := DBMS_RANDOM.VALUE;
    IF v_out <= c_corte THEN
      v_estado := CASE WHEN r < 0.12 THEN 'CANCELADA' ELSE 'COMPLETADA' END;
    ELSIF v_in <= c_corte THEN
      v_estado := 'CONFIRMADA';   -- estadía en curso
    ELSE
      v_estado := CASE WHEN r < 0.12 THEN 'CANCELADA' WHEN r < 0.45 THEN 'PENDIENTE' ELSE 'CONFIRMADA' END;
    END IF;

    -- Número de habitaciones: la mayoría 1, algunos grupos 2 a 4
    r := DBMS_RANDOM.VALUE;
    v_n_hab := CASE WHEN r < 0.86 THEN 1 WHEN r < 0.96 THEN 2 WHEN r < 0.99 THEN 3 ELSE 4 END;
    v_ini   := v_aloj_hab_ini(ia);
    v_cnt   := v_aloj_hab_n(ia);
    v_n_hab := LEAST(v_n_hab, v_cnt);

    -- Busca habitaciones libres recorriendo desde una posición aleatoria
    v_start := TRUNC(DBMS_RANDOM.VALUE(0, v_cnt));
    v_n_lin := 0;
    FOR j IN 0 .. v_cnt - 1 LOOP
      EXIT WHEN v_n_lin = v_n_hab;
      k := v_ini + MOD(v_start + j, v_cnt);
      v_l_in := v_in;
      -- Algún integrante del grupo llega un día después
      IF v_n_lin > 0 AND v_noches > 1 AND DBMS_RANDOM.VALUE < 0.15 THEN
        v_l_in := v_in + 1;
      END IF;
      -- Las canceladas no ocupan; las demás solo toman habitaciones libres
      IF v_estado = 'CANCELADA' OR libre(v_hab_id(k), v_l_in, v_out) THEN
        v_n_lin := v_n_lin + 1;
        v_lin_k(v_n_lin)  := k;
        v_lin_in(v_n_lin) := v_l_in;
      END IF;
    END LOOP;
    CONTINUE WHEN v_n_lin = 0;   -- alojamiento lleno esas noches: se intenta otra combinación

    -- Fecha en que se hizo la reserva (anticipación mayor en temporada alta)
    r := DBMS_RANDOM.VALUE;
    v_lead := CASE WHEN r < 0.20 THEN TRUNC(DBMS_RANDOM.VALUE(0, 3))
                   WHEN r < 0.55 THEN TRUNC(DBMS_RANDOM.VALUE(3, 15))
                   WHEN r < 0.85 THEN TRUNC(DBMS_RANDOM.VALUE(15, 45))
                   ELSE               TRUNC(DBMS_RANDOM.VALUE(45, 120)) END;
    IF v_cal_cat(d) = 'ALTA' THEN
      v_lead := v_lead + TRUNC(DBMS_RANDOM.VALUE(0, 20));
    END IF;
    v_freserva := v_in - v_lead + DBMS_RANDOM.VALUE(0.30, 0.95);
    IF TRUNC(v_freserva) > c_corte THEN
      -- Nadie puede haber reservado después de "hoy"
      v_freserva := c_corte - TRUNC(DBMS_RANDOM.VALUE(0, 30)) + DBMS_RANDOM.VALUE(0.30, 0.60);
    END IF;

    -- Fecha de cancelación entre la reserva y el check-in (y no después del corte)
    v_fcancel := NULL;
    IF v_estado = 'CANCELADA' THEN
      w := LEAST(v_in, c_corte + 0.99) - v_freserva;
      v_fcancel := v_freserva + DBMS_RANDOM.VALUE(0, GREATEST(w, 0.001));
    END IF;

    -- Cliente: sesgado para que unos clientes reserven mucho más que otros
    v_id_cli := v_cli_id(TRUNC(v_n_cli * POWER(DBMS_RANDOM.VALUE, 1.6)) + 1);

    INSERT INTO reserva (id_cliente, id_alojamiento, fecha_reserva, fecha_checkin, fecha_checkout, estado, fecha_cancelacion)
    VALUES (v_id_cli, v_aloj_id(ia), v_freserva, v_in, v_out, v_estado, v_fcancel)
    RETURNING id_reserva INTO v_id_res;
    v_reservas := v_reservas + 1;

    -- Líneas de habitación con valor calculado noche por noche
    v_total := 0;
    v_tot_huesp := 0;
    FOR j IN 1 .. v_n_lin LOOP
      k := v_lin_k(j);
      v_valor     := valor_estadia(v_hab_id(k), v_lin_in(j), v_out);
      v_huespedes := TRUNC(DBMS_RANDOM.VALUE(1, v_hab_cap(k) + 1));
      INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion, fecha_checkin, fecha_checkout,
                                      num_huespedes, valor_estadia)
      VALUES (v_id_res, v_aloj_id(ia), v_hab_id(k), v_lin_in(j), v_out, v_huespedes, v_valor);
      v_total     := v_total + v_valor;
      v_tot_huesp := v_tot_huesp + v_huespedes;
      IF v_estado <> 'CANCELADA' THEN
        ocupar(v_hab_id(k), v_lin_in(j), v_out);
      END IF;
    END LOOP;

    -- Servicios del mismo alojamiento (0 a 4 distintos, cantidad hasta 6)
    r := DBMS_RANDOM.VALUE;
    v_n_srv := CASE WHEN r < 0.10 THEN 0 WHEN r < 0.28 THEN 1 WHEN r < 0.58 THEN 2 WHEN r < 0.85 THEN 3 ELSE 4 END;
    v_ini   := v_aloj_srv_ini(ia);
    v_cnt   := v_aloj_srv_n(ia);
    v_n_srv := LEAST(v_n_srv, v_cnt);
    v_start := TRUNC(DBMS_RANDOM.VALUE(0, v_cnt));
    FOR j IN 0 .. v_n_srv - 1 LOOP
      k := v_ini + MOD(v_start + j, v_cnt);
      v_cant := TRUNC(DBMS_RANDOM.VALUE(1, LEAST(v_tot_huesp, 6) + 1));
      INSERT INTO reserva_servicio (id_reserva, id_servicio, id_alojamiento, cantidad, precio_unitario)
      VALUES (v_id_res, v_srv_id(k), v_aloj_id(ia), v_cant, v_srv_precio(k));
      v_total := v_total + v_cant * v_srv_precio(k);
      v_lineas_srv := v_lineas_srv + 1;
    END LOOP;

    -- Pagos según el estado
    r := DBMS_RANDOM.VALUE;
    v_anticipo := ROUND(v_total * DBMS_RANDOM.VALUE(0.30, 0.50));
    IF v_estado = 'COMPLETADA' THEN
      IF r < 0.45 THEN
        -- Pago único al reservar
        pagar(v_id_res, v_freserva + 0.01, v_total, metodo_pago(FALSE), 'EXITOSO');
      ELSIF r < 0.85 THEN
        -- Anticipo al reservar + saldo al llegar
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, metodo_pago(FALSE), 'EXITOSO');
        pagar(v_id_res, v_in + 0.60, v_total - v_anticipo, metodo_pago(TRUE), 'EXITOSO');
      ELSE
        -- Primer intento rechazado, segundo exitoso
        pagar(v_id_res, v_freserva + 0.005, v_total, metodo_pago(FALSE), 'FALLIDO');
        pagar(v_id_res, v_freserva + 0.02, v_total, metodo_pago(FALSE), 'EXITOSO');
      END IF;

    ELSIF v_estado = 'CONFIRMADA' THEN
      IF r < 0.25 THEN
        pagar(v_id_res, v_freserva + 0.01, v_total, metodo_pago(FALSE), 'EXITOSO');
      ELSE
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, metodo_pago(FALSE), 'EXITOSO');
        IF v_in <= c_corte THEN
          -- Estadía en curso: el saldo ya se pagó al llegar
          pagar(v_id_res, v_in + 0.60, v_total - v_anticipo, metodo_pago(TRUE), 'EXITOSO');
        ELSE
          -- Saldo programado para el día de llegada
          pagar(v_id_res, v_in + 0.60, v_total - v_anticipo, metodo_pago(TRUE), 'PENDIENTE');
        END IF;
      END IF;

    ELSIF v_estado = 'PENDIENTE' THEN
      IF r < 0.30 THEN
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, metodo_pago(FALSE), 'PENDIENTE');
      ELSIF r < 0.50 THEN
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, metodo_pago(FALSE), 'FALLIDO');
      END IF;   -- el resto aún no registra pagos

    ELSE  -- CANCELADA
      IF r < 0.60 THEN
        v_metodo := metodo_pago(FALSE);
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, v_metodo, 'EXITOSO');
        -- Regla de reembolso: más de 5 días antes del check-in => 80 %
        IF v_in - TRUNC(v_fcancel) > 5 THEN
          pagar(v_id_res,
                GREATEST(v_fcancel, LEAST(v_fcancel + DBMS_RANDOM.VALUE(0.5, 3), c_corte + 0.9)),
                v_anticipo * 0.8, v_metodo, 'REEMBOLSADO');
        END IF;
      ELSIF r < 0.80 THEN
        pagar(v_id_res, v_freserva + 0.01, v_anticipo, metodo_pago(FALSE), 'FALLIDO');
      END IF;
    END IF;

    -- Reseña: solo reservas completadas, con probabilidad propia del alojamiento
    IF v_estado = 'COMPLETADA' AND DBMS_RANDOM.VALUE < v_aloj_p_resena(ia) THEN
      v_calif := ROUND(v_aloj_calidad(ia) + DBMS_RANDOM.NORMAL * 0.8);
      v_calif := GREATEST(1, LEAST(5, v_calif));
      v_coment := NULL;
      IF DBMS_RANDOM.VALUE < 0.65 THEN
        v_coment := v_comentarios((v_calif - 1) * 3 + TRUNC(DBMS_RANDOM.VALUE(1, 4)));
      END IF;
      v_fresena := LEAST(v_out + DBMS_RANDOM.VALUE(0.4, 15), c_corte + 0.9);
      INSERT INTO resena (id_reserva, calificacion, comentario, fecha_resena)
      VALUES (v_id_res, v_calif, v_coment, v_fresena);
    END IF;

    IF MOD(v_reservas, 2000) = 0 THEN
      COMMIT;
    END IF;
  END LOOP;

  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Reservas generadas: ' || v_reservas || ' · líneas de servicio: ' || v_lineas_srv ||
                       ' · intentos: ' || v_intentos);
END;
