-- 0.1 Vaciar las tablas (hijas primero) y reiniciar los consecutivos en 1
BEGIN
  -- Borrado en orden de dependencia (hijas primero)
  FOR t IN (
    SELECT column_value AS nombre
    FROM TABLE(sys.odcivarchar2list(
      'RESENA', 'RESERVA_SERVICIO', 'PAGO', 'RESERVA_HABITACION', 'RESERVA',
      'USUARIO_SISTEMA', 'SERVICIO', 'CLIENTE', 'TARIFA', 'CALENDARIO',
      'PERIODO_TEMPORADA', 'TEMPORADA', 'HABITACION', 'ALOJAMIENTO',
      'TIPO_ALOJAMIENTO', 'MUNICIPIO'))
  ) LOOP
    EXECUTE IMMEDIATE 'DELETE FROM ' || t.nombre;
  END LOOP;
  COMMIT;

  -- Reinicio de las columnas de identidad: formato 'TABLA.COLUMNA'
  FOR c IN (
    SELECT column_value AS col
    FROM TABLE(sys.odcivarchar2list(
      'MUNICIPIO.ID_MUNICIPIO', 'TIPO_ALOJAMIENTO.ID_TIPO', 'ALOJAMIENTO.ID_ALOJAMIENTO',
      'HABITACION.ID_HABITACION', 'SERVICIO.ID_SERVICIO', 'TEMPORADA.ID_TEMPORADA',
      'PERIODO_TEMPORADA.ID_PERIODO', 'TARIFA.ID_TARIFA', 'CLIENTE.ID_CLIENTE',
      'RESERVA.ID_RESERVA', 'RESERVA_HABITACION.ID_RESERVA_HAB', 'PAGO.ID_PAGO',
      'RESENA.ID_RESENA', 'USUARIO_SISTEMA.ID_USUARIO'))
  ) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || SUBSTR(c.col, 1, INSTR(c.col, '.') - 1) ||
                      ' MODIFY (' || SUBSTR(c.col, INSTR(c.col, '.') + 1) ||
                      ' GENERATED BY DEFAULT AS IDENTITY (START WITH 1))';
  END LOOP;
END;
/


