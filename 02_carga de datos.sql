-- 6. Tarifas: una por cada habitación en cada temporada (sale del cruce).
-- El valor depende del tipo de alojamiento, las estrellas, el tipo de
-- habitación, la capacidad, la temporada y el año.
-- Cada alojamiento sube distinto en temporada alta (ORA_HASH da la variación).
INSERT INTO tarifa (id_habitacion, id_temporada, valor_noche)
SELECT h.id_habitacion,
       t.id_temporada,
       ROUND(
           CASE ta.nombre
             WHEN 'Hotel'          THEN 150000
             WHEN 'Hostal'         THEN  60000
             WHEN 'Glamping'       THEN 260000
             WHEN 'Finca cafetera' THEN 170000
             ELSE                       190000
           END
         * (1 + 0.15 * (a.estrellas - 3))
         * CASE h.tipo_habitacion
             WHEN 'SENCILLA' THEN 0.70
             WHEN 'DOBLE'    THEN 1.00
             WHEN 'SUITE'    THEN 1.60
             ELSE                 1.35
           END
         * (1 + 0.08 * GREATEST(h.capacidad - 2, 0))
         * (0.90 + MOD(ORA_HASH(h.id_habitacion), 21) / 100)
         * CASE t.categoria
             WHEN 'ALTA'  THEN 1.15 + MOD(ORA_HASH(a.id_alojamiento), 46) / 100
             WHEN 'MEDIA' THEN 1.00
             ELSE              0.95 - MOD(ORA_HASH(a.id_alojamiento * 7), 21) / 100
           END
         * CASE t.anio WHEN 2024 THEN 0.92 WHEN 2025 THEN 1.00 ELSE 1.07 END
       , -3) AS valor_noche
FROM   habitacion h
JOIN   alojamiento a       ON a.id_alojamiento = h.id_alojamiento
JOIN   tipo_alojamiento ta ON ta.id_tipo = a.id_tipo
CROSS JOIN temporada t;

COMMIT;


