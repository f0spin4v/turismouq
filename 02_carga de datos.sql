-- 4. Servicios
-- Cada alojamiento toma de 2 a 6 servicios de la lista de su tipo.
-- El precio cambia un poco de un alojamiento a otro.
-- Formato de la lista: 'nombre|precio'
DECLARE
  v_pool   sys.odcivarchar2list;
  v_n      PLS_INTEGER;
  v_start  PLS_INTEGER;
  v_item   VARCHAR2(200);
  v_nombre VARCHAR2(60);
  v_precio NUMBER;
BEGIN
  FOR a IN (SELECT al.id_alojamiento, al.nombre_comercial, t.nombre AS tipo
            FROM alojamiento al JOIN tipo_alojamiento t ON t.id_tipo = al.id_tipo
            ORDER BY al.id_alojamiento)
  LOOP
    IF a.tipo = 'Hotel' THEN
      v_pool := sys.odcivarchar2list('Desayuno buffet|38000', 'Transporte al aeropuerto El Edén|65000',
                'Spa y masajes|120000', 'Parqueadero|20000', 'Cena romántica|180000', 'Lavandería|25000');
      v_n := TRUNC(DBMS_RANDOM.VALUE(4, 7));
    ELSIF a.tipo = 'Finca cafetera' THEN
      v_pool := sys.odcivarchar2list('Desayuno campesino|25000', 'Tour del café|55000', 'Cabalgata|70000',
                'Almuerzo típico|35000', 'Transporte al Parque del Café|60000', 'Alquiler de bicicletas|40000');
      v_n := TRUNC(DBMS_RANDOM.VALUE(2, 6));
    ELSIF a.tipo = 'Glamping' THEN
      v_pool := sys.odcivarchar2list('Desayuno a la cama|45000', 'Jacuzzi privado|90000', 'Kit de fogata|30000',
                'Avistamiento de aves|60000', 'Decoración de aniversario|110000', 'Tour Valle de Cocora|85000');
      v_n := TRUNC(DBMS_RANDOM.VALUE(3, 6));
    ELSIF a.tipo = 'Hostal' THEN
      v_pool := sys.odcivarchar2list('Desayuno|15000', 'Alquiler de bicicletas|35000', 'Tour Valle de Cocora|75000',
                'Lavandería|15000', 'Clase de barismo|50000', 'Tour guiado por el pueblo|30000');
      v_n := TRUNC(DBMS_RANDOM.VALUE(3, 6));
    ELSE
      v_pool := sys.odcivarchar2list('Desayuno|28000', 'Asado campestre|65000', 'Transporte desde Armenia|70000',
                'Tour del café|55000', 'Piscina climatizada|40000');
      v_n := TRUNC(DBMS_RANDOM.VALUE(2, 5));
    END IF;

    -- Toma v_n servicios consecutivos del catálogo desde una posición aleatoria
    v_start := TRUNC(DBMS_RANDOM.VALUE(0, v_pool.COUNT));
    FOR j IN 0 .. v_n - 1 LOOP
      v_item   := v_pool(MOD(v_start + j, v_pool.COUNT) + 1);
      v_nombre := SUBSTR(v_item, 1, INSTR(v_item, '|') - 1);
      v_precio := ROUND(TO_NUMBER(SUBSTR(v_item, INSTR(v_item, '|') + 1)) * DBMS_RANDOM.VALUE(0.85, 1.25), -3);
      INSERT INTO servicio (id_alojamiento, nombre, descripcion, precio)
      VALUES (a.id_alojamiento, v_nombre, v_nombre || ' ofrecido por ' || a.nombre_comercial, v_precio);
    END LOOP;
  END LOOP;
  COMMIT;
END;
