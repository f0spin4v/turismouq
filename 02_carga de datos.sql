-- Calendario: expande cada periodo en un registro por día.
-- La PK de CALENDARIO (fecha) hace fallar esta sentencia si dos periodos se solapan.
INSERT INTO calendario (fecha, id_periodo, id_temporada)
SELECT p.fecha_inicio + n.k, p.id_periodo, p.id_temporada
FROM   periodo_temporada p
JOIN  (SELECT LEVEL - 1 AS k FROM dual CONNECT BY LEVEL <= 366) n
       ON n.k <= p.fecha_fin - p.fecha_inicio;

-- Verifica que el calendario no tenga huecos (regla: cada noche tiene una temporada)
DECLARE
  v_dias      NUMBER;
  v_esperados NUMBER;
BEGIN
  SELECT COUNT(*), MAX(fecha) - MIN(fecha) + 1 INTO v_dias, v_esperados FROM calendario;
  IF v_dias <> v_esperados THEN
    RAISE_APPLICATION_ERROR(-20010, 'El calendario tiene huecos: ' || v_dias || ' de ' || v_esperados || ' días');
  END IF;
  DBMS_OUTPUT.PUT_LINE('Calendario completo: ' || v_dias || ' días sin huecos ni solapes');
END;
