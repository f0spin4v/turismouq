SELECT 'PAGO',             COUNT(*), 25000 FROM pago               UNION ALL
SELECT 'SERVICIO',         COUNT(*), 30    FROM servicio           UNION ALL
SELECT 'RESERVA_SERVICIO', COUNT(*), 40000 FROM reserva_servicio   UNION ALL
SELECT 'RESENA',           COUNT(*), NULL  FROM resena             UNION ALL
SELECT 'USUARIO_SISTEMA',  COUNT(*), 10    FROM usuario_sistema;

-- 10.2 Tarifas: debe haber exactamente habitaciones x temporadas
SELECT (SELECT COUNT(*) FROM habitacion) * (SELECT COUNT(*) FROM temporada) AS tarifas_esperadas,
       (SELECT COUNT(*) FROM tarifa) AS tarifas_cargadas
FROM dual;

-- 10.3 Reseñas: al menos 40 % de las reservas completadas
SELECT COUNT(r.id_resena) AS resenas,
       COUNT(*)           AS completadas,
       ROUND(100 * COUNT(r.id_resena) / NULLIF(COUNT(*), 0), 1) AS porcentaje
FROM reserva rv
LEFT JOIN resena r ON r.id_reserva = rv.id_reserva
WHERE rv.estado = 'COMPLETADA';

-- 10.4 Reglas: todos los conteos deben dar 0
SELECT 'Solapes entre reservas activas' AS regla, COUNT(*) AS violaciones
FROM reserva_habitacion a
JOIN reserva ra ON ra.id_reserva = a.id_reserva
JOIN reserva_habitacion b ON b.id_habitacion = a.id_habitacion
                         AND b.id_reserva_hab > a.id_reserva_hab
                         AND a.fecha_checkin  < b.fecha_checkout
                         AND b.fecha_checkin  < a.fecha_checkout
JOIN reserva rb ON rb.id_reserva = b.id_reserva
WHERE ra.estado <> 'CANCELADA' AND rb.estado <> 'CANCELADA'
UNION ALL
SELECT 'Reseñas de reservas no completadas', COUNT(*)
FROM resena r JOIN reserva rv ON rv.id_reserva = r.id_reserva
WHERE rv.estado <> 'COMPLETADA' OR r.fecha_resena < rv.fecha_checkout
UNION ALL
SELECT 'Completadas con checkout futuro', COUNT(*)
FROM reserva WHERE estado = 'COMPLETADA' AND fecha_checkout > DATE '2026-09-29'
UNION ALL
SELECT 'Líneas fuera del rango de su reserva', COUNT(*)
FROM reserva_habitacion l JOIN reserva rv ON rv.id_reserva = l.id_reserva
WHERE l.fecha_checkin < rv.fecha_checkin OR l.fecha_checkout > rv.fecha_checkout
UNION ALL
SELECT 'Huéspedes por encima de la capacidad', COUNT(*)
FROM reserva_habitacion l JOIN habitacion h ON h.id_habitacion = l.id_habitacion
WHERE l.num_huespedes > h.capacidad
UNION ALL
SELECT 'Completadas sin pagar el total', COUNT(*)
FROM reserva rv
JOIN (SELECT id_reserva, SUM(valor_estadia) AS valor
      FROM reserva_habitacion GROUP BY id_reserva) e ON e.id_reserva = rv.id_reserva
LEFT JOIN (SELECT id_reserva, SUM(cantidad * precio_unitario) AS valor
           FROM reserva_servicio GROUP BY id_reserva) s ON s.id_reserva = rv.id_reserva
LEFT JOIN (SELECT id_reserva, SUM(monto) AS valor
           FROM pago WHERE estado = 'EXITOSO' GROUP BY id_reserva) p ON p.id_reserva = rv.id_reserva
WHERE rv.estado = 'COMPLETADA'
AND   NVL(p.valor, 0) < e.valor + NVL(s.valor, 0)
UNION ALL
SELECT 'Reembolsos con 5 días o menos de anticipación', COUNT(*)
FROM pago p JOIN reserva rv ON rv.id_reserva = p.id_reserva
WHERE p.estado = 'REEMBOLSADO' AND rv.fecha_checkin - TRUNC(rv.fecha_cancelacion) <= 5;

-- 10.5 Asimetría: reservas por municipio y por año (deben ser muy distintas)
SELECT m.nombre AS municipio,
       COUNT(CASE WHEN EXTRACT(YEAR FROM r.fecha_checkin) = 2024 THEN 1 END) AS r2024,
       COUNT(CASE WHEN EXTRACT(YEAR FROM r.fecha_checkin) = 2025 THEN 1 END) AS r2025,
       COUNT(CASE WHEN EXTRACT(YEAR FROM r.fecha_checkin) = 2026 THEN 1 END) AS r2026,
       COUNT(*) AS total
FROM reserva r
JOIN alojamiento a ON a.id_alojamiento = r.id_alojamiento
JOIN municipio m   ON m.id_municipio = a.id_municipio
GROUP BY m.nombre
ORDER BY total DESC;
