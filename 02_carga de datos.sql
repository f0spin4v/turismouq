-- 3. Habitaciones
-- Hoteles grandes de 30 a 40 (numeradas por piso) y pequeños de 15 a 25.
-- Hostales 8 a 14, glampings 4 a 8, fincas 3 a 6, casas campestres 3 a 5.
DECLARE
  v_n         PLS_INTEGER;
  v_tipo_hab  VARCHAR2(10);
  v_cap       PLS_INTEGER;
  v_num       VARCHAR2(10);
  v_desc      VARCHAR2(300);
  r           NUMBER;
BEGIN
  FOR a IN (SELECT al.id_alojamiento, al.estrellas, t.nombre AS tipo, m.nombre AS municipio
            FROM alojamiento al
            JOIN tipo_alojamiento t ON t.id_tipo = al.id_tipo
            JOIN municipio m        ON m.id_municipio = al.id_municipio
            ORDER BY al.id_alojamiento)
  LOOP
    -- Número de habitaciones según el tipo de alojamiento
    IF a.tipo = 'Hotel' THEN
      IF a.estrellas >= 4 OR a.municipio = 'Armenia' THEN
        v_n := TRUNC(DBMS_RANDOM.VALUE(30, 41));
      ELSE
        v_n := TRUNC(DBMS_RANDOM.VALUE(15, 26));
      END IF;
    ELSIF a.tipo = 'Hostal'   THEN v_n := TRUNC(DBMS_RANDOM.VALUE(8, 15));
    ELSIF a.tipo = 'Glamping' THEN v_n := TRUNC(DBMS_RANDOM.VALUE(4, 9));
    ELSIF a.tipo = 'Finca cafetera' THEN v_n := TRUNC(DBMS_RANDOM.VALUE(3, 7));
    ELSE v_n := TRUNC(DBMS_RANDOM.VALUE(3, 6));
    END IF;

    FOR i IN 1 .. v_n LOOP
      -- Tipo de habitación coherente con el alojamiento
      r := DBMS_RANDOM.VALUE;
      IF a.tipo = 'Hotel' THEN
        v_tipo_hab := CASE WHEN r < 0.25 THEN 'SENCILLA' WHEN r < 0.80 THEN 'DOBLE' ELSE 'SUITE' END;
      ELSIF a.tipo = 'Hostal' THEN
        v_tipo_hab := CASE WHEN r < 0.45 THEN 'SENCILLA' WHEN r < 0.85 THEN 'DOBLE' ELSE 'SUITE' END;
      ELSIF a.tipo = 'Glamping' THEN
        v_tipo_hab := CASE WHEN r < 0.70 THEN 'CABANA' ELSE 'SUITE' END;
      ELSIF a.tipo = 'Finca cafetera' THEN
        v_tipo_hab := CASE WHEN r < 0.45 THEN 'DOBLE' WHEN r < 0.75 THEN 'CABANA' ELSE 'SUITE' END;
      ELSE
        v_tipo_hab := CASE WHEN r < 0.50 THEN 'DOBLE' WHEN r < 0.80 THEN 'SUITE' ELSE 'CABANA' END;
      END IF;

      -- Capacidad según el tipo de habitación
      v_cap := CASE v_tipo_hab
                 WHEN 'SENCILLA' THEN 1
                 WHEN 'DOBLE'    THEN TRUNC(DBMS_RANDOM.VALUE(2, 4))
                 WHEN 'SUITE'    THEN TRUNC(DBMS_RANDOM.VALUE(3, 7))
                 ELSE                 TRUNC(DBMS_RANDOM.VALUE(2, 7))
               END;

      -- Hoteles numeran por piso (10 habitaciones por piso); los demás 1, 2, 3...
      IF a.tipo = 'Hotel' THEN
        v_num := TO_CHAR((TRUNC((i - 1) / 10) + 1) * 100 + MOD(i - 1, 10) + 1);
      ELSE
        v_num := TO_CHAR(i);
      END IF;

      v_desc := CASE v_tipo_hab
                  WHEN 'SENCILLA' THEN 'Habitación sencilla con cama individual'
                  WHEN 'DOBLE'    THEN 'Habitación doble para ' || v_cap || ' personas'
                  WHEN 'SUITE'    THEN 'Suite amplia para ' || v_cap || ' personas'
                  ELSE                 'Cabaña independiente para ' || v_cap || ' personas'
                END;

      INSERT INTO habitacion (id_alojamiento, numero, capacidad, tipo_habitacion, descripcion)
      VALUES (a.id_alojamiento, v_num, v_cap, v_tipo_hab, v_desc);
    END LOOP;
  END LOOP;
  COMMIT;
END;
