-- Borrar las tablas si ya existen, de las hijas a las padres.
-- Si una tabla no existe (ORA-00942) se sigue de largo.
BEGIN
  FOR t IN (
    SELECT column_value AS nombre
    FROM TABLE(sys.odcivarchar2list(
      'RESENA', 'RESERVA_SERVICIO', 'PAGO', 'RESERVA_HABITACION', 'RESERVA',
      'USUARIO_SISTEMA', 'SERVICIO', 'CLIENTE', 'TARIFA', 'CALENDARIO',
      'PERIODO_TEMPORADA', 'TEMPORADA', 'HABITACION', 'ALOJAMIENTO',
      'TIPO_ALOJAMIENTO', 'MUNICIPIO'))
  ) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.nombre || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
