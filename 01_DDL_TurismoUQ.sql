-- Catálogos: municipio y tipo de alojamiento

-- MUNICIPIO: los 12 municipios del Quindío donde hay oferta de alojamiento.
CREATE TABLE municipio (
  id_municipio  NUMBER(3)     GENERATED BY DEFAULT AS IDENTITY,
  nombre        VARCHAR2(60)  NOT NULL,
  CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
  CONSTRAINT uq_municipio_nombre UNIQUE (nombre)
);
COMMENT ON TABLE  municipio        IS 'Municipios del Quindío donde operan los alojamientos';
COMMENT ON COLUMN municipio.nombre IS 'Nombre oficial del municipio (único)';


-- TIPO_ALOJAMIENTO: finca cafetera, hotel, glamping, hostal, etc.
CREATE TABLE tipo_alojamiento (
  id_tipo      NUMBER(3)      GENERATED BY DEFAULT AS IDENTITY,
  nombre       VARCHAR2(40)   NOT NULL,
  descripcion  VARCHAR2(200),
  CONSTRAINT pk_tipo_alojamiento        PRIMARY KEY (id_tipo),
  CONSTRAINT uq_tipo_alojamiento_nombre UNIQUE (nombre)
);
COMMENT ON TABLE tipo_alojamiento IS 'Clasificación del alojamiento (finca cafetera, hotel, glamping, hostal...)';


--Alojamientos, habitaciones y servicios

-- ALOJAMIENTO: establecimiento que ofrece habitaciones. Pertenece a un
-- municipio y a un tipo. Las estrellas son autoasignadas (1 a 5).
CREATE TABLE alojamiento (
  id_alojamiento    NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  id_municipio      NUMBER(3)      NOT NULL,
  id_tipo           NUMBER(3)      NOT NULL,
  nombre_comercial  VARCHAR2(100)  NOT NULL,
  direccion         VARCHAR2(150)  NOT NULL,
  estrellas         NUMBER(1)      NOT NULL,
  telefono          VARCHAR2(20)   NOT NULL,
  correo            VARCHAR2(120),
  CONSTRAINT pk_alojamiento           PRIMARY KEY (id_alojamiento),
  CONSTRAINT fk_alojamiento_municipio FOREIGN KEY (id_municipio) REFERENCES municipio (id_municipio),
  CONSTRAINT fk_alojamiento_tipo      FOREIGN KEY (id_tipo)      REFERENCES tipo_alojamiento (id_tipo),
  -- Dos alojamientos del mismo municipio no pueden llamarse igual
  CONSTRAINT uq_alojamiento_nombre    UNIQUE (nombre_comercial, id_municipio),
  CONSTRAINT ck_alojamiento_estrellas CHECK (estrellas BETWEEN 1 AND 5),
  CONSTRAINT ck_alojamiento_correo    CHECK (correo IS NULL OR correo LIKE '%_@_%._%')
);
COMMENT ON TABLE  alojamiento           IS 'Establecimiento de hospedaje (finca, hotel, glamping, hostal) ubicado en un municipio';
COMMENT ON COLUMN alojamiento.estrellas IS 'Calificación de 1 a 5 que el propio alojamiento se autoasigna (distinta de las reseñas)';


-- HABITACION: unidad reservable dentro de un alojamiento.
-- El número es único solo dentro de su alojamiento.
CREATE TABLE habitacion (
  id_habitacion    NUMBER(8)      GENERATED BY DEFAULT AS IDENTITY,
  id_alojamiento   NUMBER(6)      NOT NULL,
  numero           VARCHAR2(10)   NOT NULL,
  capacidad        NUMBER(2)      NOT NULL,
  tipo_habitacion  VARCHAR2(10)   NOT NULL,
  descripcion      VARCHAR2(300),
  CONSTRAINT pk_habitacion             PRIMARY KEY (id_habitacion),
  CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_habitacion_numero      UNIQUE (id_alojamiento, numero),
  -- Clave candidata usada por la FK compuesta de RESERVA_HABITACION:
  -- garantiza que la habitación reservada sea del alojamiento de la reserva
  CONSTRAINT uq_habitacion_aloj        UNIQUE (id_habitacion, id_alojamiento),
  CONSTRAINT ck_habitacion_capacidad   CHECK (capacidad BETWEEN 1 AND 20),
  CONSTRAINT ck_habitacion_tipo        CHECK (tipo_habitacion IN ('SENCILLA', 'DOBLE', 'SUITE', 'CABANA'))
);
COMMENT ON TABLE  habitacion           IS 'Habitación reservable de un alojamiento; el número no se repite dentro del mismo alojamiento';
COMMENT ON COLUMN habitacion.capacidad IS 'Máximo de huéspedes permitido en la habitación';


-- SERVICIO: servicio complementario propio de un alojamiento.
-- El desayuno del hotel X y el del hotel Y son servicios distintos.
CREATE TABLE servicio (
  id_servicio     NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
  id_alojamiento  NUMBER(6)      NOT NULL,
  nombre          VARCHAR2(60)   NOT NULL,
  descripcion     VARCHAR2(300),
  precio          NUMBER(10,2)   NOT NULL,
  CONSTRAINT pk_servicio             PRIMARY KEY (id_servicio),
  CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_servicio_nombre      UNIQUE (id_alojamiento, nombre),
  -- Clave candidata para la FK compuesta de RESERVA_SERVICIO
  CONSTRAINT uq_servicio_aloj        UNIQUE (id_servicio, id_alojamiento),
  CONSTRAINT ck_servicio_precio      CHECK (precio >= 0)
);
COMMENT ON TABLE servicio IS 'Servicio complementario (desayuno, tour, transporte, spa...) ofrecido por un alojamiento específico';


-- Temporadas, calendario y tarifas (decisión de diseño 1)
-- TEMPORADA es la categoría por año (alta, media, baja).
-- PERIODO_TEMPORADA tiene las fechas de cada temporada.
-- CALENDARIO dice a qué temporada pertenece cada día.
-- TARIFA es el valor por noche de cada habitación en cada temporada.
-- Con CALENDARIO y TARIFA se calcula la estadía noche por noche.

-- TEMPORADA: combinación única de año y categoría.
CREATE TABLE temporada (
  id_temporada  NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
  anio          NUMBER(4)    NOT NULL,
  categoria     VARCHAR2(5)  NOT NULL,
  CONSTRAINT pk_temporada           PRIMARY KEY (id_temporada),
  CONSTRAINT uq_temporada_anio_cat  UNIQUE (anio, categoria),
  CONSTRAINT ck_temporada_anio      CHECK (anio BETWEEN 2020 AND 2100),
  CONSTRAINT ck_temporada_categoria CHECK (categoria IN ('ALTA', 'MEDIA', 'BAJA'))
);
COMMENT ON TABLE  temporada      IS 'Temporada turística por año y categoría (ALTA, MEDIA, BAJA); las tarifas se definen sobre ella';
COMMENT ON COLUMN temporada.anio IS 'Año de la temporada. Diciembre-enero se asigna al año en que inicia el periodo';


-- PERIODO_TEMPORADA: cada rango de fechas concreto de una temporada.
CREATE TABLE periodo_temporada (
  id_periodo    NUMBER(5)     GENERATED BY DEFAULT AS IDENTITY,
  id_temporada  NUMBER(4)     NOT NULL,
  nombre        VARCHAR2(80)  NOT NULL,
  fecha_inicio  DATE          NOT NULL,
  fecha_fin     DATE          NOT NULL,
  CONSTRAINT pk_periodo_temporada   PRIMARY KEY (id_periodo),
  CONSTRAINT fk_periodo_temporada   FOREIGN KEY (id_temporada) REFERENCES temporada (id_temporada),
  CONSTRAINT uq_periodo_nombre      UNIQUE (nombre),
  -- Clave candidata para la FK compuesta de CALENDARIO
  CONSTRAINT uq_periodo_temp        UNIQUE (id_periodo, id_temporada),
  CONSTRAINT ck_periodo_rango       CHECK (fecha_fin >= fecha_inicio),
  -- Las fechas son días completos, sin componente de hora
  CONSTRAINT ck_periodo_fechas_dia  CHECK (fecha_inicio = TRUNC(fecha_inicio) AND fecha_fin = TRUNC(fecha_fin))
);
COMMENT ON TABLE periodo_temporada IS 'Rango de fechas concreto de una temporada (ej. Semana Santa 2025 dentro de ALTA 2025)';


-- CALENDARIO: un día por fila, asignado a exactamente un periodo y temporada.
-- Año y mes son columnas virtuales para agrupar sin funciones en las consultas.
CREATE TABLE calendario (
  fecha         DATE       NOT NULL,
  id_periodo    NUMBER(5)  NOT NULL,
  id_temporada  NUMBER(4)  NOT NULL,
  anio          NUMBER(4)  GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha)) VIRTUAL,
  mes           NUMBER(2)  GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha)) VIRTUAL,
  CONSTRAINT pk_calendario          PRIMARY KEY (fecha),
  -- FK compuesta: la temporada del día debe ser la de su periodo
  CONSTRAINT fk_calendario_periodo  FOREIGN KEY (id_periodo, id_temporada)
                                    REFERENCES periodo_temporada (id_periodo, id_temporada),
  CONSTRAINT ck_calendario_dia      CHECK (fecha = TRUNC(fecha))
);
COMMENT ON TABLE  calendario       IS 'Un registro por día; asigna cada noche a una sola temporada. Base del cálculo noche por noche';
COMMENT ON COLUMN calendario.fecha IS 'Día calendario (PK): impide que dos periodos de temporada se solapen';


-- TARIFA: valor por noche de una habitación en una temporada.
-- No es un porcentaje sobre un precio base: cada alojamiento fija su valor.
CREATE TABLE tarifa (
  id_tarifa      NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
  id_habitacion  NUMBER(8)     NOT NULL,
  id_temporada   NUMBER(4)     NOT NULL,
  valor_noche    NUMBER(10,2)  NOT NULL,
  CONSTRAINT pk_tarifa            PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_tarifa_habitacion FOREIGN KEY (id_habitacion) REFERENCES habitacion (id_habitacion),
  CONSTRAINT fk_tarifa_temporada  FOREIGN KEY (id_temporada)  REFERENCES temporada (id_temporada),
  -- Una sola tarifa por habitación y temporada
  CONSTRAINT uq_tarifa_hab_temp   UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_valor      CHECK (valor_noche > 0)
);
COMMENT ON TABLE tarifa IS 'Valor por noche de cada habitación en cada temporada (cruce habitación x temporada)';


-- Clientes y reservas (decisión de diseño 2)
-- RESERVA es el encabezado y RESERVA_HABITACION tiene una línea por habitación,
-- cada una con sus fechas. Las FK compuestas con id_alojamiento no dejan mezclar
-- habitaciones ni servicios de otro alojamiento en la misma reserva.

-- CLIENTE: persona que reserva. Puede venir de cualquier ciudad.
CREATE TABLE cliente (
  id_cliente      NUMBER(8)      GENERATED BY DEFAULT AS IDENTITY,
  tipo_documento  VARCHAR2(3)    NOT NULL,
  num_documento   VARCHAR2(20)   NOT NULL,
  nombres         VARCHAR2(60)   NOT NULL,
  apellidos       VARCHAR2(60)   NOT NULL,
  correo          VARCHAR2(120)  NOT NULL,
  telefono        VARCHAR2(20)   NOT NULL,
  ciudad_origen   VARCHAR2(60)   NOT NULL,
  fecha_registro  DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_cliente           PRIMARY KEY (id_cliente),
  CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, num_documento),
  CONSTRAINT uq_cliente_correo    UNIQUE (correo),
  -- CC cédula, CE cédula de extranjería, PA pasaporte, PPT permiso por protección temporal
  CONSTRAINT ck_cliente_tipo_doc  CHECK (tipo_documento IN ('CC', 'CE', 'PA', 'PPT')),
  CONSTRAINT ck_cliente_correo    CHECK (correo LIKE '%_@_%._%')
);
COMMENT ON TABLE cliente IS 'Cliente registrado en la plataforma; un cliente puede tener muchas reservas';


-- RESERVA: encabezado de la reserva. Sus fechas son el rango general
-- (mínimo check-in y máximo check-out de sus líneas).
CREATE TABLE reserva (
  id_reserva         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_cliente         NUMBER(8)     NOT NULL,
  id_alojamiento     NUMBER(6)     NOT NULL,
  fecha_reserva      DATE          NOT NULL,
  fecha_checkin      DATE          NOT NULL,
  fecha_checkout     DATE          NOT NULL,
  estado             VARCHAR2(12)  DEFAULT 'PENDIENTE' NOT NULL,
  fecha_cancelacion  DATE,
  CONSTRAINT pk_reserva             PRIMARY KEY (id_reserva),
  CONSTRAINT fk_reserva_cliente     FOREIGN KEY (id_cliente)     REFERENCES cliente (id_cliente),
  CONSTRAINT fk_reserva_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  -- Clave candidata para las FK compuestas de las líneas de la reserva
  CONSTRAINT uq_reserva_aloj        UNIQUE (id_reserva, id_alojamiento),
  CONSTRAINT ck_reserva_estado      CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
  CONSTRAINT ck_reserva_fechas      CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reserva_dias        CHECK (fecha_checkin = TRUNC(fecha_checkin) AND fecha_checkout = TRUNC(fecha_checkout)),
  -- No se puede reservar para una fecha ya pasada respecto al momento de reservar
  CONSTRAINT ck_reserva_anticipo    CHECK (TRUNC(fecha_reserva) <= fecha_checkin),
  -- Solo las reservas canceladas tienen fecha de cancelación, y es posterior a la reserva
  CONSTRAINT ck_reserva_cancelacion CHECK (
        (estado =  'CANCELADA' AND fecha_cancelacion IS NOT NULL AND fecha_cancelacion >= fecha_reserva)
     OR (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL))
);
COMMENT ON TABLE  reserva                   IS 'Reserva de un cliente en un alojamiento; agrupa una o varias habitaciones';
COMMENT ON COLUMN reserva.estado            IS 'PENDIENTE, CONFIRMADA, CANCELADA o COMPLETADA. Solo CONFIRMADA y COMPLETADA ocupan la habitación';
COMMENT ON COLUMN reserva.fecha_cancelacion IS 'Fecha en que se canceló; determina el derecho a reembolso (más de 5 días antes del check-in = 80 %)';


-- RESERVA_HABITACION: cada habitación incluida en una reserva, con fechas
-- propias (un integrante del grupo puede llegar un día después).
CREATE TABLE reserva_habitacion (
  id_reserva_hab  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_reserva      NUMBER(10)    NOT NULL,
  id_alojamiento  NUMBER(6)     NOT NULL,
  id_habitacion   NUMBER(8)     NOT NULL,
  fecha_checkin   DATE          NOT NULL,
  fecha_checkout  DATE          NOT NULL,
  num_huespedes   NUMBER(2)     NOT NULL,
  valor_estadia   NUMBER(12,2)  NOT NULL,
  CONSTRAINT pk_reserva_habitacion PRIMARY KEY (id_reserva_hab),
  -- La reserva y la habitación deben pertenecer al mismo alojamiento
  CONSTRAINT fk_reshab_reserva     FOREIGN KEY (id_reserva, id_alojamiento)
                                   REFERENCES reserva (id_reserva, id_alojamiento),
  CONSTRAINT fk_reshab_habitacion  FOREIGN KEY (id_habitacion, id_alojamiento)
                                   REFERENCES habitacion (id_habitacion, id_alojamiento),
  -- Una habitación aparece una sola vez por reserva
  CONSTRAINT uq_reshab_reserva_hab UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_reshab_fechas      CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reshab_dias        CHECK (fecha_checkin = TRUNC(fecha_checkin) AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reshab_huespedes   CHECK (num_huespedes >= 1),
  CONSTRAINT ck_reshab_valor       CHECK (valor_estadia >= 0)
);
COMMENT ON TABLE  reserva_habitacion               IS 'Línea de reserva: una habitación con sus fechas propias dentro del rango de la reserva';
COMMENT ON COLUMN reserva_habitacion.valor_estadia IS 'Valor calculado noche por noche con la tarifa vigente al reservar (precio congelado)';


-- PAGO: abonos de una reserva (anticipo, saldo) y reembolsos.
CREATE TABLE pago (
  id_pago     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_reserva  NUMBER(10)    NOT NULL,
  fecha_pago  DATE          NOT NULL,
  monto       NUMBER(12,2)  NOT NULL,
  metodo      VARCHAR2(16)  NOT NULL,
  estado      VARCHAR2(12)  NOT NULL,
  CONSTRAINT pk_pago         PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
  CONSTRAINT ck_pago_monto   CHECK (monto > 0),
  CONSTRAINT ck_pago_metodo  CHECK (metodo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO')),
  CONSTRAINT ck_pago_estado  CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE', 'REEMBOLSADO'))
);
COMMENT ON TABLE  pago        IS 'Pago o abono de una reserva. Una reserva está pagada cuando sus pagos EXITOSOS cubren estadía + servicios';
COMMENT ON COLUMN pago.estado IS 'REEMBOLSADO registra la devolución al cliente por cancelación (80 % si cancela con más de 5 días)';


-- RESERVA_SERVICIO: servicios contratados en una reserva, con cantidad.
CREATE TABLE reserva_servicio (
  id_reserva       NUMBER(10)    NOT NULL,
  id_servicio      NUMBER(6)     NOT NULL,
  id_alojamiento   NUMBER(6)     NOT NULL,
  cantidad         NUMBER(3)     NOT NULL,
  precio_unitario  NUMBER(10,2)  NOT NULL,
  CONSTRAINT pk_reserva_servicio PRIMARY KEY (id_reserva, id_servicio),
  -- El servicio debe ser del mismo alojamiento de la reserva
  CONSTRAINT fk_resserv_reserva  FOREIGN KEY (id_reserva, id_alojamiento)
                                 REFERENCES reserva (id_reserva, id_alojamiento),
  CONSTRAINT fk_resserv_servicio FOREIGN KEY (id_servicio, id_alojamiento)
                                 REFERENCES servicio (id_servicio, id_alojamiento),
  CONSTRAINT ck_resserv_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_resserv_precio   CHECK (precio_unitario >= 0)
);
COMMENT ON TABLE  reserva_servicio                 IS 'Servicios complementarios incluidos en una reserva, con cantidad pedida';
COMMENT ON COLUMN reserva_servicio.precio_unitario IS 'Precio del servicio al momento de reservar (precio congelado)';


-- RESENA: opinión del cliente sobre una estadía. Atada a la reserva:
-- una reseña por reserva, y solo sobre reservas COMPLETADAS (validado
-- en la carga y, en la Entrega 2, por disparador).
CREATE TABLE resena (
  id_resena     NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY,
  id_reserva    NUMBER(10)      NOT NULL,
  calificacion  NUMBER(1)       NOT NULL,
  comentario    VARCHAR2(1000),
  fecha_resena  DATE            NOT NULL,
  CONSTRAINT pk_resena              PRIMARY KEY (id_resena),
  CONSTRAINT fk_resena_reserva      FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
  CONSTRAINT uq_resena_reserva      UNIQUE (id_reserva),
  CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5)
);
COMMENT ON TABLE resena IS 'Reseña de un cliente sobre el alojamiento de una reserva completada (calificación 1 a 5)';


-- Usuarios del sistema

-- USUARIO_SISTEMA: administradores de la plataforma y encargados de
-- alojamiento. Un encargado gestiona un único alojamiento; un
-- administrador no está atado a ninguno.
CREATE TABLE usuario_sistema (
  id_usuario       NUMBER(5)      GENERATED BY DEFAULT AS IDENTITY,
  username         VARCHAR2(30)   NOT NULL,
  nombre_completo  VARCHAR2(120)  NOT NULL,
  correo           VARCHAR2(120)  NOT NULL,
  rol              VARCHAR2(10)   NOT NULL,
  id_alojamiento   NUMBER(6),
  activo           CHAR(1)        DEFAULT 'S' NOT NULL,
  fecha_creacion   DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_usuario_sistema  PRIMARY KEY (id_usuario),
  CONSTRAINT fk_usuario_aloj     FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_usuario_username UNIQUE (username),
  CONSTRAINT uq_usuario_correo   UNIQUE (correo),
  CONSTRAINT ck_usuario_rol      CHECK (rol IN ('ADMIN', 'ENCARGADO')),
  CONSTRAINT ck_usuario_activo   CHECK (activo IN ('S', 'N')),
  -- ADMIN sin alojamiento; ENCARGADO obligatoriamente con alojamiento
  CONSTRAINT ck_usuario_rol_aloj CHECK (
        (rol = 'ADMIN'     AND id_alojamiento IS NULL)
     OR (rol = 'ENCARGADO' AND id_alojamiento IS NOT NULL))
);
COMMENT ON TABLE usuario_sistema IS 'Usuario interno de la plataforma: administrador o encargado de un alojamiento';


-- Revisión: deben salir las 16 tablas
SELECT t.table_name,
       COUNT(c.constraint_name) AS restricciones
FROM   user_tables t
LEFT JOIN user_constraints c ON c.table_name = t.table_name
WHERE  t.table_name IN ('MUNICIPIO', 'TIPO_ALOJAMIENTO', 'ALOJAMIENTO', 'HABITACION',
                        'SERVICIO', 'TEMPORADA', 'PERIODO_TEMPORADA', 'CALENDARIO',
                        'TARIFA', 'CLIENTE', 'RESERVA', 'RESERVA_HABITACION', 'PAGO',
                        'RESERVA_SERVICIO', 'RESENA', 'USUARIO_SISTEMA')
GROUP BY t.table_name
ORDER BY t.table_name;
