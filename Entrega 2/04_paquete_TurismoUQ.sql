-- El paquete pkg_turismouq junta:
--   fn_valor_estadia       valor de una estadía noche por noche
--   sp_crear_reserva       crea una reserva validando fechas, capacidad y disponibilidad
--   sp_liquidacion_mensual liquidación del mes por alojamiento, con un cursor explícito
--
-- Errores propios (RAISE_APPLICATION_ERROR):
--   -20001  el checkout es igual o anterior al check-in
--   -20002  la habitación no está disponible en esas fechas
--   -20003  se pidieron más huéspedes de los que caben en la habitación
--   -20004  la habitación no existe
--   -20005  hay noches sin tarifa o fuera del calendario
--   -20006  el cliente no existe
--   -20007  el check-in ya pasó
--   -20008  año o mes inválido en la liquidación
--   -20009  estado inválido para una reserva nueva

SET SERVEROUTPUT ON
SET DEFINE OFF


-- 1. Tabla donde se guarda el resultado de la liquidación mensual
-- Se borra si ya existe, así el script se puede correr varias veces.
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE liquidacion_mensual PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE liquidacion_mensual (
  id_liquidacion     NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  anio               NUMBER(4)      NOT NULL,
  mes                NUMBER(2)      NOT NULL,
  id_alojamiento     NUMBER(6)      NOT NULL,
  reservas           NUMBER(6)      NOT NULL,
  noches             NUMBER(8)      NOT NULL,
  ingreso_estadia    NUMBER(14,2)   NOT NULL,
  ingreso_servicios  NUMBER(14,2)   NOT NULL,
  total              NUMBER(14,2)   NOT NULL,
  comision           NUMBER(14,2)   NOT NULL,
  valor_a_pagar      NUMBER(14,2)   NOT NULL,
  fecha_generacion   DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_liquidacion       PRIMARY KEY (id_liquidacion),
  CONSTRAINT fk_liquidacion_aloj  FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uq_liquidacion       UNIQUE (anio, mes, id_alojamiento),
  CONSTRAINT ck_liquidacion_mes   CHECK (mes BETWEEN 1 AND 12)
);
COMMENT ON TABLE liquidacion_mensual IS 'Resultado de la liquidación mensual por alojamiento (lo llena sp_liquidacion_mensual)';


-- 2. Especificación del paquete: lo que se ve desde afuera
CREATE OR REPLACE PACKAGE pkg_turismouq AS

  -- Comisión que cobra la plataforma sobre lo que factura cada alojamiento.
  -- Es un supuesto del equipo: el enunciado no da el porcentaje.
  c_comision CONSTANT NUMBER := 0.15;

  -- Excepciones con nombre para los errores propios.
  -- Así quien llame el procedimiento puede atraparlas por nombre.
  e_fechas_invalidas  EXCEPTION;
  e_no_disponible     EXCEPTION;
  e_capacidad         EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_fechas_invalidas, -20001);
  PRAGMA EXCEPTION_INIT(e_no_disponible,    -20002);
  PRAGMA EXCEPTION_INIT(e_capacidad,        -20003);

  -- Valor de una estadía: suma la tarifa de cada noche según su temporada.
  -- La noche del checkout no se cobra.
  FUNCTION fn_valor_estadia (
    p_id_habitacion  IN habitacion.id_habitacion%TYPE,
    p_fecha_in       IN DATE,
    p_fecha_out      IN DATE
  ) RETURN NUMBER;

  -- Crea una reserva de una habitación. Devuelve el id de la reserva nueva.
  -- No hace COMMIT: eso lo decide quien lo llama.
  PROCEDURE sp_crear_reserva (
    p_id_cliente     IN  cliente.id_cliente%TYPE,
    p_id_habitacion  IN  habitacion.id_habitacion%TYPE,
    p_fecha_in       IN  DATE,
    p_fecha_out      IN  DATE,
    p_num_huespedes  IN  NUMBER,
    p_id_reserva     OUT reserva.id_reserva%TYPE,
    p_estado         IN  VARCHAR2 DEFAULT 'CONFIRMADA'
  );

  -- Liquida un mes: por cada alojamiento suma lo de las reservas completadas
  -- cuyo checkout cae en ese mes, descuenta la comisión y guarda el resultado
  -- en LIQUIDACION_MENSUAL. Si p_id_alojamiento es NULL liquida todos.
  PROCEDURE sp_liquidacion_mensual (
    p_anio            IN NUMBER,
    p_mes             IN NUMBER,
    p_id_alojamiento  IN NUMBER DEFAULT NULL
  );

END pkg_turismouq;
/


-- 3. Cuerpo del paquete: el código de cada parte
CREATE OR REPLACE PACKAGE BODY pkg_turismouq AS

  -- -------------------------------------------------------------------
  -- fn_valor_estadia
  -- Recorre las noches de la estadía una por una. Para cada noche busca en
  -- CALENDARIO a qué temporada pertenece y trae de TARIFA cuánto vale esa
  -- habitación en esa temporada. Así, si la estadía empieza en temporada
  -- media y termina en alta, cada noche se cobra con su propia tarifa.
  -- -------------------------------------------------------------------
  FUNCTION fn_valor_estadia (
    p_id_habitacion  IN habitacion.id_habitacion%TYPE,
    p_fecha_in       IN DATE,
    p_fecha_out      IN DATE
  ) RETURN NUMBER
  IS
    v_total        NUMBER := 0;
    v_noches       PLS_INTEGER;
    v_con_tarifa   PLS_INTEGER := 0;
    v_existe       PLS_INTEGER;
  BEGIN
    IF p_fecha_in IS NULL OR p_fecha_out IS NULL
       OR TRUNC(p_fecha_out) <= TRUNC(p_fecha_in) THEN
      RAISE_APPLICATION_ERROR(-20001,
        'El checkout debe ser posterior al check-in');
    END IF;

    SELECT COUNT(*) INTO v_existe
    FROM   habitacion
    WHERE  id_habitacion = p_id_habitacion;

    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(-20004,
        'La habitación ' || p_id_habitacion || ' no existe');
    END IF;

    v_noches := TRUNC(p_fecha_out) - TRUNC(p_fecha_in);

    -- Una vuelta por noche: del check-in hasta el día antes del checkout
    FOR n IN (SELECT c.fecha, t.valor_noche
              FROM   calendario c
              JOIN   tarifa t ON t.id_temporada  = c.id_temporada
                             AND t.id_habitacion = p_id_habitacion
              WHERE  c.fecha >= TRUNC(p_fecha_in)
              AND    c.fecha <  TRUNC(p_fecha_out)
              ORDER BY c.fecha)
    LOOP
      v_total      := v_total + n.valor_noche;
      v_con_tarifa := v_con_tarifa + 1;
    END LOOP;

    -- Si alguna noche no encontró tarifa, el valor estaría incompleto
    IF v_con_tarifa < v_noches THEN
      RAISE_APPLICATION_ERROR(-20005,
        'Hay ' || (v_noches - v_con_tarifa) ||
        ' noche(s) sin tarifa o fuera del calendario');
    END IF;

    RETURN v_total;
  END fn_valor_estadia;


  -- -------------------------------------------------------------------
  -- sp_crear_reserva
  -- Valida en este orden: fechas, estado, cliente, habitación, capacidad y
  -- disponibilidad. Si todo está bien, calcula el valor con fn_valor_estadia
  -- y guarda el encabezado (RESERVA) y la línea (RESERVA_HABITACION).
  -- -------------------------------------------------------------------
  PROCEDURE sp_crear_reserva (
    p_id_cliente     IN  cliente.id_cliente%TYPE,
    p_id_habitacion  IN  habitacion.id_habitacion%TYPE,
    p_fecha_in       IN  DATE,
    p_fecha_out      IN  DATE,
    p_num_huespedes  IN  NUMBER,
    p_id_reserva     OUT reserva.id_reserva%TYPE,
    p_estado         IN  VARCHAR2 DEFAULT 'CONFIRMADA'
  )
  IS
    v_in         DATE := TRUNC(p_fecha_in);
    v_out        DATE := TRUNC(p_fecha_out);
    v_id_aloj    habitacion.id_alojamiento%TYPE;
    v_capacidad  habitacion.capacidad%TYPE;
    v_existe     PLS_INTEGER;
    v_choques    PLS_INTEGER;
    v_valor      NUMBER;
  BEGIN
    -- 1. Fechas
    IF p_fecha_in IS NULL OR p_fecha_out IS NULL OR v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(-20001,
        'El checkout (' || TO_CHAR(v_out, 'DD/MM/YYYY') ||
        ') debe ser posterior al check-in (' || TO_CHAR(v_in, 'DD/MM/YYYY') || ')');
    END IF;

    IF v_in < TRUNC(SYSDATE) THEN
      RAISE_APPLICATION_ERROR(-20007,
        'No se puede reservar con check-in en el pasado (' || TO_CHAR(v_in, 'DD/MM/YYYY') || ')');
    END IF;

    -- 2. Una reserva nueva solo puede nacer pendiente o confirmada
    IF p_estado NOT IN ('PENDIENTE', 'CONFIRMADA') THEN
      RAISE_APPLICATION_ERROR(-20009,
        'Una reserva nueva debe ser PENDIENTE o CONFIRMADA, no ' || p_estado);
    END IF;

    -- 3. Cliente
    SELECT COUNT(*) INTO v_existe
    FROM   cliente
    WHERE  id_cliente = p_id_cliente;

    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(-20006,
        'El cliente ' || p_id_cliente || ' no existe');
    END IF;

    -- 4. Habitación. FOR UPDATE bloquea la fila mientras se reserva, para que
    --    otra sesión no reserve la misma habitación al mismo tiempo.
    BEGIN
      SELECT id_alojamiento, capacidad
      INTO   v_id_aloj, v_capacidad
      FROM   habitacion
      WHERE  id_habitacion = p_id_habitacion
      FOR UPDATE;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20004,
          'La habitación ' || p_id_habitacion || ' no existe');
    END;

    -- 5. Capacidad
    IF p_num_huespedes IS NULL OR p_num_huespedes < 1
       OR p_num_huespedes > v_capacidad THEN
      RAISE_APPLICATION_ERROR(-20003,
        'La habitación ' || p_id_habitacion || ' admite máximo ' || v_capacidad ||
        ' huésped(es) y se pidieron ' || NVL(TO_CHAR(p_num_huespedes), 'ninguno'));
    END IF;

    -- 6. Disponibilidad: dos estadías chocan si una empieza antes de que la
    --    otra termine y termina después de que la otra empieza. Solo ocupan
    --    las reservas CONFIRMADA y COMPLETADA (regla de negocio 8).
    SELECT COUNT(*) INTO v_choques
    FROM   reserva_habitacion l
    JOIN   reserva r ON r.id_reserva = l.id_reserva
    WHERE  l.id_habitacion  = p_id_habitacion
    AND    r.estado IN ('CONFIRMADA', 'COMPLETADA')
    AND    l.fecha_checkin  < v_out
    AND    l.fecha_checkout > v_in;

    IF v_choques > 0 THEN
      RAISE_APPLICATION_ERROR(-20002,
        'La habitación ' || p_id_habitacion || ' no está disponible del ' ||
        TO_CHAR(v_in, 'DD/MM/YYYY') || ' al ' || TO_CHAR(v_out, 'DD/MM/YYYY'));
    END IF;

    -- 7. Valor noche por noche (se guarda congelado en la línea)
    v_valor := fn_valor_estadia(p_id_habitacion, v_in, v_out);

    -- 8. Guardar encabezado y línea
    INSERT INTO reserva (id_cliente, id_alojamiento, fecha_reserva,
                         fecha_checkin, fecha_checkout, estado)
    VALUES (p_id_cliente, v_id_aloj, SYSDATE, v_in, v_out, p_estado)
    RETURNING id_reserva INTO p_id_reserva;

    INSERT INTO reserva_habitacion (id_reserva, id_alojamiento, id_habitacion,
                                    fecha_checkin, fecha_checkout,
                                    num_huespedes, valor_estadia)
    VALUES (p_id_reserva, v_id_aloj, p_id_habitacion,
            v_in, v_out, p_num_huespedes, v_valor);
  END sp_crear_reserva;


  -- -------------------------------------------------------------------
  -- sp_liquidacion_mensual
  -- Usa un cursor explícito con tres parámetros (año, mes y alojamiento).
  -- El cursor trae una fila por alojamiento con lo que facturó en el mes;
  -- el ciclo la recorre, calcula la comisión y guarda la liquidación.
  -- -------------------------------------------------------------------
  PROCEDURE sp_liquidacion_mensual (
    p_anio            IN NUMBER,
    p_mes             IN NUMBER,
    p_id_alojamiento  IN NUMBER DEFAULT NULL
  )
  IS
    CURSOR c_liquidacion (cp_anio NUMBER, cp_mes NUMBER, cp_id_aloj NUMBER) IS
      SELECT a.id_alojamiento,
             a.nombre_comercial,
             NVL(e.reservas, 0)   AS reservas,
             NVL(e.noches, 0)     AS noches,
             NVL(e.estadia, 0)    AS ingreso_estadia,
             NVL(s.servicios, 0)  AS ingreso_servicios
      FROM   alojamiento a
      -- Estadías de reservas completadas con checkout en el mes
      LEFT JOIN (SELECT r.id_alojamiento,
                        COUNT(DISTINCT r.id_reserva)                AS reservas,
                        SUM(l.fecha_checkout - l.fecha_checkin)     AS noches,
                        SUM(l.valor_estadia)                        AS estadia
                 FROM   reserva r
                 JOIN   reserva_habitacion l ON l.id_reserva = r.id_reserva
                 WHERE  r.estado = 'COMPLETADA'
                 AND    r.fecha_checkout >= TO_DATE(cp_anio || LPAD(cp_mes, 2, '0') || '01', 'YYYYMMDD')
                 AND    r.fecha_checkout <  ADD_MONTHS(TO_DATE(cp_anio || LPAD(cp_mes, 2, '0') || '01', 'YYYYMMDD'), 1)
                 GROUP BY r.id_alojamiento) e
             ON e.id_alojamiento = a.id_alojamiento
      -- Servicios de esas mismas reservas
      LEFT JOIN (SELECT r.id_alojamiento,
                        SUM(rs.cantidad * rs.precio_unitario)       AS servicios
                 FROM   reserva r
                 JOIN   reserva_servicio rs ON rs.id_reserva = r.id_reserva
                 WHERE  r.estado = 'COMPLETADA'
                 AND    r.fecha_checkout >= TO_DATE(cp_anio || LPAD(cp_mes, 2, '0') || '01', 'YYYYMMDD')
                 AND    r.fecha_checkout <  ADD_MONTHS(TO_DATE(cp_anio || LPAD(cp_mes, 2, '0') || '01', 'YYYYMMDD'), 1)
                 GROUP BY r.id_alojamiento) s
             ON s.id_alojamiento = a.id_alojamiento
      WHERE  cp_id_aloj IS NULL OR a.id_alojamiento = cp_id_aloj
      ORDER BY a.id_alojamiento;

    r_liq          c_liquidacion%ROWTYPE;
    v_total        NUMBER;
    v_comision     NUMBER;
    v_filas        PLS_INTEGER := 0;
    v_suma_total   NUMBER := 0;
    v_suma_pagar   NUMBER := 0;
  BEGIN
    IF p_anio IS NULL OR p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
      RAISE_APPLICATION_ERROR(-20008,
        'Año o mes inválido: ' || p_anio || '-' || p_mes);
    END IF;

    -- Si ese mes ya se había liquidado, se borra y se vuelve a calcular
    DELETE FROM liquidacion_mensual
    WHERE  anio = p_anio
    AND    mes  = p_mes
    AND    (p_id_alojamiento IS NULL OR id_alojamiento = p_id_alojamiento);

    DBMS_OUTPUT.PUT_LINE('Liquidación ' || p_anio || '-' || LPAD(p_mes, 2, '0') ||
                         ' (comisión ' || (c_comision * 100) || ' %)');
    DBMS_OUTPUT.PUT_LINE(RPAD('Alojamiento', 36) || LPAD('Reservas', 9) ||
                         LPAD('Total', 17) || LPAD('A pagar', 17));

    OPEN c_liquidacion(p_anio, p_mes, p_id_alojamiento);
    LOOP
      FETCH c_liquidacion INTO r_liq;
      EXIT WHEN c_liquidacion%NOTFOUND;

      v_total    := r_liq.ingreso_estadia + r_liq.ingreso_servicios;
      v_comision := ROUND(v_total * c_comision);

      INSERT INTO liquidacion_mensual (anio, mes, id_alojamiento, reservas, noches,
                                       ingreso_estadia, ingreso_servicios,
                                       total, comision, valor_a_pagar)
      VALUES (p_anio, p_mes, r_liq.id_alojamiento, r_liq.reservas, r_liq.noches,
              r_liq.ingreso_estadia, r_liq.ingreso_servicios,
              v_total, v_comision, v_total - v_comision);

      DBMS_OUTPUT.PUT_LINE(RPAD(r_liq.nombre_comercial, 36) ||
                           LPAD(r_liq.reservas, 9) ||
                           LPAD(TO_CHAR(v_total, 'FM999G999G999G990'), 17) ||
                           LPAD(TO_CHAR(v_total - v_comision, 'FM999G999G999G990'), 17));

      v_filas      := v_filas + 1;
      v_suma_total := v_suma_total + v_total;
      v_suma_pagar := v_suma_pagar + (v_total - v_comision);
    END LOOP;
    CLOSE c_liquidacion;

    DBMS_OUTPUT.PUT_LINE(RPAD('TOTAL (' || v_filas || ' alojamientos)', 45) ||
                         LPAD(TO_CHAR(v_suma_total, 'FM999G999G999G990'), 17) ||
                         LPAD(TO_CHAR(v_suma_pagar, 'FM999G999G999G990'), 17));
  EXCEPTION
    WHEN OTHERS THEN
      -- Si algo falla con el cursor abierto, se cierra antes de salir
      IF c_liquidacion%ISOPEN THEN
        CLOSE c_liquidacion;
      END IF;
      RAISE;
  END sp_liquidacion_mensual;

END pkg_turismouq;
/

