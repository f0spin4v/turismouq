SET SERVEROUTPUT ON
SET DEFINE OFF


-- 1. Tabla de auditoría de tarifas
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE auditoria_tarifa PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE auditoria_tarifa (
  id_auditoria        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  id_tarifa           NUMBER(8)      NOT NULL,
  id_habitacion       NUMBER(8)      NOT NULL,
  id_temporada        NUMBER(4)      NOT NULL,
  valor_anterior      NUMBER(10,2)   NOT NULL,
  valor_nuevo         NUMBER(10,2)   NOT NULL,
  usuario_bd          VARCHAR2(128)  NOT NULL,
  usuario_so          VARCHAR2(128),
  equipo              VARCHAR2(128),
  fecha_cambio        TIMESTAMP      NOT NULL,
  filas_en_sentencia  NUMBER(8)      NOT NULL,
  CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria)
);
COMMENT ON TABLE  auditoria_tarifa                    IS 'Historial de cambios de valor en TARIFA (lo llena trg_tarifa_auditoria)';
COMMENT ON COLUMN auditoria_tarifa.usuario_bd         IS 'Usuario de Oracle que hizo el cambio (quién)';
COMMENT ON COLUMN auditoria_tarifa.usuario_so         IS 'Usuario del sistema operativo del equipo que se conectó';
COMMENT ON COLUMN auditoria_tarifa.fecha_cambio       IS 'Momento del cambio (cuándo)';
COMMENT ON COLUMN auditoria_tarifa.filas_en_sentencia IS 'Cuántas tarifas cambió la misma sentencia UPDATE';


-- 2. Disparador de sentencia: auditoría de TARIFA
--
-- Un disparador de sentencia normal se ejecuta una sola vez por UPDATE, pero
-- no puede ver :OLD ni :NEW, así que no sabría el valor anterior ni el nuevo.
-- Por eso usamos un disparador COMPUESTO (COMPOUND TRIGGER):
--   AFTER EACH ROW   solo anota en memoria cada tarifa que cambió
--   AFTER STATEMENT  cuando termina la sentencia, escribe la auditoría
-- La escritura pasa una vez por sentencia, como pide el enunciado, y con los
-- valores de cada fila.
CREATE OR REPLACE TRIGGER trg_tarifa_auditoria
FOR UPDATE OF valor_noche ON tarifa
COMPOUND TRIGGER

  TYPE t_cambio IS RECORD (
    id_tarifa      tarifa.id_tarifa%TYPE,
    id_habitacion  tarifa.id_habitacion%TYPE,
    id_temporada   tarifa.id_temporada%TYPE,
    anterior       tarifa.valor_noche%TYPE,
    nuevo          tarifa.valor_noche%TYPE
  );
  TYPE t_cambios IS TABLE OF t_cambio INDEX BY PLS_INTEGER;

  v_cambios  t_cambios;
  v_n        PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    v_cambios.DELETE;
    v_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    -- Solo se anota si el valor de verdad cambió
    IF :OLD.valor_noche <> :NEW.valor_noche THEN
      v_n := v_n + 1;
      v_cambios(v_n).id_tarifa     := :NEW.id_tarifa;
      v_cambios(v_n).id_habitacion := :NEW.id_habitacion;
      v_cambios(v_n).id_temporada  := :NEW.id_temporada;
      v_cambios(v_n).anterior      := :OLD.valor_noche;
      v_cambios(v_n).nuevo         := :NEW.valor_noche;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    FOR i IN 1 .. v_n LOOP
      INSERT INTO auditoria_tarifa (id_tarifa, id_habitacion, id_temporada,
                                    valor_anterior, valor_nuevo,
                                    usuario_bd, usuario_so, equipo,
                                    fecha_cambio, filas_en_sentencia)
      VALUES (v_cambios(i).id_tarifa, v_cambios(i).id_habitacion, v_cambios(i).id_temporada,
              v_cambios(i).anterior, v_cambios(i).nuevo,
              USER,
              SYS_CONTEXT('USERENV', 'OS_USER'),
              SYS_CONTEXT('USERENV', 'HOST'),
              SYSTIMESTAMP,
              v_n);
    END LOOP;
    v_cambios.DELETE;
  END AFTER STATEMENT;

END trg_tarifa_auditoria;
/

SHOW ERRORS TRIGGER trg_tarifa_auditoria


-- 3. Disparador de fila: impedir solapes
--
-- Antes de guardar cada línea de RESERVA_HABITACION revisa si esa habitación
-- ya tiene una reserva CONFIRMADA o COMPLETADA que choque con las fechas.
-- Si choca, cancela la inserción con el error -20010.
-- Las reservas canceladas no se revisan porque no ocupan la habitación.
--
-- Se dispara solo al INSERTAR ("registrar una reserva"). Consultar la misma
-- tabla desde un disparador de fila funciona con INSERT ... VALUES de una
-- fila, que es como insertan sp_crear_reserva y la carga. Un UPDATE o un
-- INSERT de varias filas daría el error de tabla mutante (ORA-04091).
CREATE OR REPLACE TRIGGER trg_reshab_solape
BEFORE INSERT ON reserva_habitacion
FOR EACH ROW
DECLARE
  v_estado   reserva.estado%TYPE;
  v_choques  PLS_INTEGER;
  v_otra     reserva.id_reserva%TYPE;
BEGIN
  -- Estado de la reserva a la que pertenece la línea nueva
  BEGIN
    SELECT estado INTO v_estado
    FROM   reserva
    WHERE  id_reserva = :NEW.id_reserva;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN;  -- la llave foránea se encarga de rechazarla
  END;

  IF v_estado = 'CANCELADA' THEN
    RETURN;
  END IF;

  SELECT COUNT(*), MIN(l.id_reserva)
  INTO   v_choques, v_otra
  FROM   reserva_habitacion l
  JOIN   reserva r ON r.id_reserva = l.id_reserva
  WHERE  l.id_habitacion  = :NEW.id_habitacion
  AND    l.id_reserva    <> :NEW.id_reserva
  AND    r.estado IN ('CONFIRMADA', 'COMPLETADA')
  AND    l.fecha_checkin  < :NEW.fecha_checkout
  AND    l.fecha_checkout > :NEW.fecha_checkin;

  IF v_choques > 0 THEN
    RAISE_APPLICATION_ERROR(-20010,
      'La habitación ' || :NEW.id_habitacion || ' ya está ocupada entre el ' ||
      TO_CHAR(:NEW.fecha_checkin, 'DD/MM/YYYY') || ' y el ' ||
      TO_CHAR(:NEW.fecha_checkout, 'DD/MM/YYYY') ||
      ' (choca con la reserva ' || v_otra || ')');
  END IF;
END;
/

SHOW ERRORS TRIGGER trg_reshab_solape


-- 4. Revisión: los dos disparadores deben quedar ENABLED y VALID
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name,
       t.status, o.status AS compilacion
FROM   user_triggers t
JOIN   user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
WHERE  t.trigger_name IN ('TRG_TARIFA_AUDITORIA', 'TRG_RESHAB_SOLAPE')
ORDER BY t.trigger_name;
