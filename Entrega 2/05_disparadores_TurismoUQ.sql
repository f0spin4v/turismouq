SET SERVEROUTPUT ON
SET DEFINE OFF


-- 1. Tabla de auditoría de tarifas
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE auditoria_tarifa PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE auditoria_tarifa (
  id_auditoria        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  operacion           VARCHAR2(6)    NOT NULL,
  id_tarifa           NUMBER(8)      NOT NULL,
  id_habitacion       NUMBER(8)      NOT NULL,
  id_temporada        NUMBER(4)      NOT NULL,
  valor_anterior      NUMBER(10,2),
  valor_nuevo         NUMBER(10,2),
  usuario_bd          VARCHAR2(128)  NOT NULL,
  usuario_so          VARCHAR2(128),
  equipo              VARCHAR2(128),
  fecha_cambio        TIMESTAMP      NOT NULL,
  filas_en_sentencia  NUMBER(8)      NOT NULL,
  CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria),
  CONSTRAINT ck_auditoria_operacion CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
  -- INSERT no tiene valor anterior y DELETE no tiene valor nuevo
  CONSTRAINT ck_auditoria_valores CHECK (
       (operacion = 'INSERT' AND valor_anterior IS NULL AND valor_nuevo IS NOT NULL)
    OR (operacion = 'UPDATE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NOT NULL)
    OR (operacion = 'DELETE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NULL))
);
COMMENT ON TABLE  auditoria_tarifa                    IS 'Historial de tarifas creadas, cambiadas y borradas (lo llena trg_tarifa_auditoria)';
COMMENT ON COLUMN auditoria_tarifa.operacion          IS 'INSERT, UPDATE o DELETE';
COMMENT ON COLUMN auditoria_tarifa.valor_anterior     IS 'Valor antes del cambio (vacío en un INSERT)';
COMMENT ON COLUMN auditoria_tarifa.valor_nuevo        IS 'Valor después del cambio (vacío en un DELETE)';
COMMENT ON COLUMN auditoria_tarifa.usuario_bd         IS 'Usuario de Oracle que hizo el cambio (quién)';
COMMENT ON COLUMN auditoria_tarifa.usuario_so         IS 'Usuario del sistema operativo del equipo que se conectó';
COMMENT ON COLUMN auditoria_tarifa.fecha_cambio       IS 'Momento del cambio (cuándo)';
COMMENT ON COLUMN auditoria_tarifa.filas_en_sentencia IS 'Cuántas tarifas tocó la misma sentencia';


-- 2. Disparador de sentencia: auditoría de TARIFA
--
-- Un disparador de sentencia normal se ejecuta una sola vez por sentencia,
-- pero no puede ver :OLD ni :NEW, así que no sabría los valores. Por eso
-- usamos un disparador COMPUESTO (COMPOUND TRIGGER):
--   AFTER EACH ROW   solo anota en memoria cada tarifa afectada
--   AFTER STATEMENT  cuando termina la sentencia, escribe toda la auditoría
--                    de una vez con FORALL
-- Cubre las tres operaciones:
--   INSERT  se anota el valor nuevo (no hay anterior)
--   UPDATE  se anota el anterior y el nuevo, solo si el valor cambió
--   DELETE  se anota el valor anterior (no hay nuevo)
CREATE OR REPLACE TRIGGER trg_tarifa_auditoria
FOR INSERT OR UPDATE OF valor_noche OR DELETE ON tarifa
COMPOUND TRIGGER

  TYPE t_cambio IS RECORD (
    operacion      VARCHAR2(6),
    id_tarifa      tarifa.id_tarifa%TYPE,
    id_habitacion  tarifa.id_habitacion%TYPE,
    id_temporada   tarifa.id_temporada%TYPE,
    anterior       tarifa.valor_noche%TYPE,
    nuevo          tarifa.valor_noche%TYPE
  );
  TYPE t_cambios IS TABLE OF t_cambio INDEX BY PLS_INTEGER;

  v_cambios  t_cambios;
  v_n        PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    v_cambios.DELETE;
    v_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    IF INSERTING THEN
      v_n := v_n + 1;
      v_cambios(v_n).operacion     := 'INSERT';
      v_cambios(v_n).id_tarifa     := :NEW.id_tarifa;
      v_cambios(v_n).id_habitacion := :NEW.id_habitacion;
      v_cambios(v_n).id_temporada  := :NEW.id_temporada;
      v_cambios(v_n).anterior      := NULL;
      v_cambios(v_n).nuevo         := :NEW.valor_noche;

    ELSIF UPDATING THEN
      -- Solo se anota si el valor de verdad cambió
      IF :OLD.valor_noche <> :NEW.valor_noche THEN
        v_n := v_n + 1;
        v_cambios(v_n).operacion     := 'UPDATE';
        v_cambios(v_n).id_tarifa     := :NEW.id_tarifa;
        v_cambios(v_n).id_habitacion := :NEW.id_habitacion;
        v_cambios(v_n).id_temporada  := :NEW.id_temporada;
        v_cambios(v_n).anterior      := :OLD.valor_noche;
        v_cambios(v_n).nuevo         := :NEW.valor_noche;
      END IF;

    ELSIF DELETING THEN
      v_n := v_n + 1;
      v_cambios(v_n).operacion     := 'DELETE';
      v_cambios(v_n).id_tarifa     := :OLD.id_tarifa;
      v_cambios(v_n).id_habitacion := :OLD.id_habitacion;
      v_cambios(v_n).id_temporada  := :OLD.id_temporada;
      v_cambios(v_n).anterior      := :OLD.valor_noche;
      v_cambios(v_n).nuevo         := NULL;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    -- FORALL manda todas las filas en un solo viaje, así un INSERT o un
    -- DELETE masivo de tarifas no se vuelve lento por la auditoría
    FORALL i IN 1 .. v_n
      INSERT INTO auditoria_tarifa (operacion, id_tarifa, id_habitacion, id_temporada,
                                    valor_anterior, valor_nuevo,
                                    usuario_bd, usuario_so, equipo,
                                    fecha_cambio, filas_en_sentencia)
      VALUES (v_cambios(i).operacion, v_cambios(i).id_tarifa,
              v_cambios(i).id_habitacion, v_cambios(i).id_temporada,
              v_cambios(i).anterior, v_cambios(i).nuevo,
              USER,
              SYS_CONTEXT('USERENV', 'OS_USER'),
              SYS_CONTEXT('USERENV', 'HOST'),
              SYSTIMESTAMP,
              v_n);
    v_cambios.DELETE;
  END AFTER STATEMENT;

END trg_tarifa_auditoria;
/

SHOW ERRORS TRIGGER trg_tarifa_auditoria


-- 3. Disparador compuesto: impedir solapes en RESERVA_HABITACION
--
-- Problema de la primera versión: un disparador FOR EACH ROW que consulta
-- su propia tabla da el error de tabla mutante (ORA-04091) con un
-- INSERT ... SELECT de varias filas o con un UPDATE, porque la tabla está
-- a medio cambiar mientras la sentencia corre.
--
-- Solución: disparador COMPUESTO.
--   AFTER EACH ROW   no consulta la tabla; solo anota el id de cada línea
--                    insertada o modificada
--   AFTER STATEMENT  la sentencia ya terminó y la tabla ya no está mutando,
--                    así que aquí sí se puede consultar. Por cada línea
--                    anotada busca otra línea de la misma habitación, de una
--                    reserva CONFIRMADA o COMPLETADA, con fechas que se crucen.
-- Si encuentra un choque lanza -20010 y Oracle deshace toda la sentencia.
--
-- Dos estadías chocan si una empieza antes de que la otra termine y termina
-- después de que la otra empieza. Las reservas canceladas no ocupan.
CREATE OR REPLACE TRIGGER trg_reshab_solape
FOR INSERT OR UPDATE OF id_habitacion, fecha_checkin, fecha_checkout, id_reserva
ON reserva_habitacion
COMPOUND TRIGGER

  TYPE t_ids IS TABLE OF reserva_habitacion.id_reserva_hab%TYPE INDEX BY PLS_INTEGER;

  v_ids  t_ids;
  v_n    PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    v_ids.DELETE;
    v_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    v_n := v_n + 1;
    v_ids(v_n) := :NEW.id_reserva_hab;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_choques  PLS_INTEGER;
    v_hab      reserva_habitacion.id_habitacion%TYPE;
    v_in       DATE;
    v_out      DATE;
    v_otra     reserva.id_reserva%TYPE;
  BEGIN
    FOR i IN 1 .. v_n LOOP
      SELECT COUNT(*), MIN(n.id_habitacion), MIN(n.fecha_checkin),
             MIN(n.fecha_checkout), MIN(o.id_reserva)
      INTO   v_choques, v_hab, v_in, v_out, v_otra
      FROM   reserva_habitacion n
      JOIN   reserva rn ON rn.id_reserva = n.id_reserva
      JOIN   reserva_habitacion o ON o.id_habitacion   = n.id_habitacion
                                 AND o.id_reserva_hab <> n.id_reserva_hab
      JOIN   reserva ro ON ro.id_reserva = o.id_reserva
      WHERE  n.id_reserva_hab = v_ids(i)
      AND    rn.estado <> 'CANCELADA'
      AND    ro.estado IN ('CONFIRMADA', 'COMPLETADA')
      AND    o.fecha_checkin  < n.fecha_checkout
      AND    o.fecha_checkout > n.fecha_checkin;

      IF v_choques > 0 THEN
        RAISE_APPLICATION_ERROR(-20010,
          'La habitación ' || v_hab || ' ya está ocupada entre el ' ||
          TO_CHAR(v_in, 'DD/MM/YYYY') || ' y el ' || TO_CHAR(v_out, 'DD/MM/YYYY') ||
          ' (choca con la reserva ' || v_otra || ')');
      END IF;
    END LOOP;
    v_ids.DELETE;
  END AFTER STATEMENT;

END trg_reshab_solape;
/

SHOW ERRORS TRIGGER trg_reshab_solape


-- 4. Revisión: los dos disparadores deben quedar ENABLED y VALID
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name,
       t.status, o.status AS compilacion
FROM   user_triggers t
JOIN   user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
WHERE  t.trigger_name IN ('TRG_TARIFA_AUDITORIA', 'TRG_RESHAB_SOLAPE')
ORDER BY t.trigger_name;
